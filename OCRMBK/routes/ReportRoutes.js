// ================= Generate Report =================
router.post("/generate", async (req, res) => {
  try {
    const {
      reportName,
      reportType,
      generatedBy,
      fromDate,
      toDate,
      totalRecords,
      status,
      summary,
      preview,
      fileName,
      fileType,
      generatedTime,
    } = req.body;

    // Validation
    if (!reportName || !reportType || !generatedBy || !fromDate || !toDate) {
      return res.status(400).json({
        success: false,
        message:
          "Report Name, Report Type, Generated By, From Date and To Date are required.",
      });
    }

    const report = new Report({
      reportName,
      reportType,
      generatedBy,
      fromDate,
      toDate,
      totalRecords,
      status,
      summary,
      preview,
      fileName,
      fileType,
      generatedTime,
    });

    await report.save();

    res.status(201).json({
      success: true,
      message: "Report Generated Successfully",
      data: report,
    });
  } catch (error) {
    console.error(error);

    res.status(500).json({
      success: false,
      message: "Internal Server Error",
      error: error.message,
    });
  }
});

