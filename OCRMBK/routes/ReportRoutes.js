const express = require("express");
const router = express.Router();

const Report = require("../models/Report");

// ================= Dashboard Summary =================
router.get("/dashboard", async (req, res) => {
  try {
    const totalReports = await Report.countDocuments();

    const generatedReports = await Report.countDocuments({
      status: "Generated",
    });

    const pendingReports = await Report.countDocuments({
      status: "Pending",
    });

    const failedReports = await Report.countDocuments({
      status: "Failed",
    });

    res.status(200).json({
      totalReports,
      generatedReports,
      pendingReports,
      failedReports,

      // Chart Data
      monthlyReports: [
        { month: "Jan", reports: 10 },
        { month: "Feb", reports: 18 },
        { month: "Mar", reports: 25 },
        { month: "Apr", reports: 20 },
        { month: "May", reports: 30 },
        { month: "Jun", reports: 28 },
        { month: "Jul", reports: totalReports },
      ],
    });
  } catch (err) {
    res.status(500).json({
      success: false,
      message: err.message,
    });
  }
});

// ================= Get All Reports =================
router.get("/", async (req, res) => {
  try {
    const reports = await Report.find().sort({ createdAt: -1 });

    res.status(200).json(reports);
  } catch (err) {
    res.status(500).json({
      success: false,
      message: err.message,
    });
  }
});

// ================= Get Report By Id =================
router.get("/:id", async (req, res) => {
  try {
    const report = await Report.findById(req.params.id);

    if (!report) {
      return res.status(404).json({
        success: false,
        message: "Report Not Found",
      });
    }

    res.status(200).json(report);
  } catch (err) {
    res.status(500).json({
      success: false,
      message: err.message,
    });
  }
});

